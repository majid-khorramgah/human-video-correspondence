"""
01_temporal_structure.py

Temporal Structure Analysis
===========================

Purpose
-------
Analyze the temporal organization of the PhySense-Human dataset
before performing image-level similarity, motion, or correspondence
analysis.

This script:

1. Locates the dataset master_index.csv automatically.
2. Loads only the columns required for temporal analysis.
3. Groups frames by source video.
4. Sorts frames by frame_id.
5. Computes temporal/frame-ID gaps.
6. Computes frames per video.
7. Estimates sequence duration.
8. Detects videos split across multiple dataset shards.
9. Builds adjacent temporal frame pairs.
10. Produces summary CSV/JSON files.
11. Produces diagnostic figures.

Important
---------
frame_id is treated as the temporal ordering variable.

If the original extraction process sampled approximately one frame
per second, EXPECTED_FRAME_INTERVAL_SECONDS can be set to 1.0.

The script does NOT assume that frame_id itself is a timestamp.
It only uses frame_id to establish temporal order and calculate
frame-ID differences.

Outputs
-------
results/temporal_statistics/
    temporal_summary.json
    video_temporal_statistics.csv
    frame_pair_statistics.csv
    temporal_gaps.csv

results/figures/
    frames_per_video_temporal.png
    frame_gap_distribution.png
    estimated_video_duration.png
    videos_per_split_temporal.png
    videos_spanning_shards.png

Author
------
PhySense-Human Research Pipeline
"""

