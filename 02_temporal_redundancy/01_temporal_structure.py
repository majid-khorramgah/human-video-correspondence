def load_master_index(master_index_path: Path) -> pd.DataFrame:

    print_step("Loading master dataset index")

    print(f"Master index:")
    print(f"  {master_index_path}")

    print()
    print("Reading required columns only...")

    try:
        df = pd.read_csv(
            master_index_path,
            usecols=REQUIRED_COLUMNS,
            low_memory=False,
        )

    except ValueError as exc:
        raise RuntimeError(
            "The master_index.csv does not contain all required "
            f"columns:\n{REQUIRED_COLUMNS}\n\n"
            f"Original error:\n{exc}"
        )

    print(
        f"Rows loaded: {format_number(len(df))}"
    )

    # --------------------------------------------------------
    # Basic cleaning
    # --------------------------------------------------------

    missing_before = df[
        ["shard", "split", "video_id", "frame_id"]
    ].isna().any(axis=1).sum()

    if missing_before > 0:
        print(
            f"WARNING: {format_number(missing_before)} rows contain "
            "missing temporal metadata."
        )

        df = df.dropna(
            subset=[
                "shard",
                "split",
                "video_id",
                "frame_id",
            ]
        ).copy()

    # Convert frame_id to numeric
    df["frame_id"] = pd.to_numeric(
        df["frame_id"],
        errors="coerce",
    )

    invalid_frame_ids = df["frame_id"].isna().sum()

    if invalid_frame_ids > 0:

        print(
            f"WARNING: {format_number(invalid_frame_ids)} rows have "
            "invalid frame_id values and will be removed."
        )

        df = df.dropna(
            subset=["frame_id"]
        ).copy()

    df["frame_id"] = df["frame_id"].astype(np.int64)

    # Normalize strings
    df["video_id"] = df["video_id"].astype(str)
    df["split"] = df["split"].astype(str)
    df["shard"] = df["shard"].astype(str)

    print(
        f"Valid temporal rows: {format_number(len(df))}"
    )

    return df


