def compute_dataset_summary(
    df: pd.DataFrame,
    video_stats: pd.DataFrame,
    gap_df: pd.DataFrame,
    pair_df: pd.DataFrame,
    duplicate_df: pd.DataFrame,
) -> Dict:

    num_frames = len(df)

    num_videos = int(
        df["video_id"].nunique()
    )

    num_shards = int(
        df["shard"].nunique()
    )

    split_frame_counts = (
        df["split"]
        .value_counts()
        .sort_index()
        .to_dict()
    )

    split_video_counts = (
        df
        .groupby("split")["video_id"]
        .nunique()
        .sort_index()
        .to_dict()
    )

    videos_spanning_shards = int(
        video_stats[
            "spans_multiple_shards"
        ].sum()
    )

    videos_with_gaps = int(
        video_stats[
            "has_frame_id_gap"
        ].sum()
    )

    total_expected_transitions = int(
        video_stats[
            "expected_transitions"
        ].sum()
    )

    total_adjacent_transitions = int(
        video_stats[
            "adjacent_transitions"
        ].sum()
    )

    global_continuity = (
        total_adjacent_transitions
        / total_expected_transitions
        if total_expected_transitions > 0
        else 1.0
    )

    summary = {
        "analysis": "temporal_structure",

        "configuration": {
            "expected_frame_interval_seconds":
                EXPECTED_FRAME_INTERVAL_SECONDS,
        },

        "dataset": {
            "num_frames": num_frames,
            "num_videos": num_videos,
            "num_shards": num_shards,
        },

        "splits": {
            "frames": {
                str(k): int(v)
                for k, v in split_frame_counts.items()
            },

            "videos": {
                str(k): int(v)
                for k, v in split_video_counts.items()
            },
        },

        "temporal_structure": {
            "total_transitions":
                int(len(pair_df)),

            "expected_transitions":
                total_expected_transitions,

            "adjacent_transitions":
                total_adjacent_transitions,

            "global_continuity_ratio":
                float(global_continuity),

            "videos_with_frame_id_gaps":
                videos_with_gaps,

            "total_temporal_gap_locations":
                int(len(gap_df)),
        },

        "video_statistics": {
            "mean_frames_per_video":
                float(
                    video_stats["num_frames"].mean()
                ),

            "median_frames_per_video":
                float(
                    video_stats["num_frames"].median()
                ),

            "min_frames_per_video":
                int(
                    video_stats["num_frames"].min()
                ),

            "max_frames_per_video":
                int(
                    video_stats["num_frames"].max()
                ),

            "mean_estimated_duration_seconds":
                float(
                    video_stats[
                        "estimated_duration_seconds"
                    ].mean()
                ),

            "median_estimated_duration_seconds":
                float(
                    video_stats[
                        "estimated_duration_seconds"
                    ].median()
                ),

            "videos_spanning_multiple_shards":
                videos_spanning_shards,
        },

        "integrity_checks": {
            "duplicate_temporal_identities":
                int(len(duplicate_df)),

            "videos_with_frame_id_gaps":
                videos_with_gaps,

            "temporal_structure_pass":
                (
                    len(duplicate_df) == 0
                    and videos_with_gaps == 0
                ),
        },
    }

    return summary


