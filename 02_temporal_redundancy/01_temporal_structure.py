def save_frames_per_video_figure(
    video_stats: pd.DataFrame,
    output_path: Path,
) -> None:

    values = (
        video_stats["num_frames"]
        .sort_values()
        .reset_index(drop=True)
    )

    if len(values) > MAX_INDIVIDUAL_VIDEOS_IN_PLOT:

        indices = np.linspace(
            0,
            len(values) - 1,
            MAX_INDIVIDUAL_VIDEOS_IN_PLOT,
            dtype=int,
        )

        values = values.iloc[
            indices
        ]

    plt.figure(
        figsize=(12, 6)
    )

    plt.plot(
        range(1, len(values) + 1),
        values,
        marker=".",
        linewidth=1,
    )

    plt.xlabel(
        "Videos (sorted by number of frames)"
    )

    plt.ylabel(
        "Number of frames"
    )

    plt.title(
        "Frames per Video"
    )

    plt.grid(
        True,
        alpha=0.3,
    )

    plt.tight_layout()

    plt.savefig(
        output_path,
        dpi=200,
    )

    plt.close()


