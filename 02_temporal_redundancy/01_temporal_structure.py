def find_project_root() -> Path:
    """
    Find the project root by searching upward for:
        01_dataset_audit
    and/or
        02_temporal_redundancy
    """

    current = Path(__file__).resolve().parent

    candidates = [current] + list(current.parents)

    for path in candidates:
        if (
            (path / "01_dataset_audit").exists()
            and (path / "02_temporal_redundancy").exists()
        ):
            return path

    raise FileNotFoundError(
        "Could not locate project root.\n"
        "Expected a directory containing both:\n"
        "  01_dataset_audit/\n"
        "  02_temporal_redundancy/"
    )


def find_master_index(project_root: Path) -> Path:
    """
    Locate the master_index.csv generated by the integrity audit.
    """

    candidates = [
        project_root
        / "01_dataset_audit"
        / "results"
        / "integrity"
        / "master_index.csv",

        project_root
        / "01_dataset_audit"
        / "01_dataset_audit"
        / "results"
        / "integrity"
        / "master_index.csv",
    ]

    for path in candidates:
        if path.exists():
            return path

    # Fallback recursive search
    matches = list(project_root.rglob("master_index.csv"))

    if len(matches) == 1:
        return matches[0]

    if len(matches) > 1:
        print("Multiple master_index.csv files found:")

        for m in matches:
            print(f"  - {m}")

        raise RuntimeError(
            "Multiple master_index.csv files found. "
            "Please keep only the intended dataset index."
        )

    raise FileNotFoundError(
        "master_index.csv was not found.\n"
        "Expected location:\n"
        "01_dataset_audit/results/integrity/master_index.csv"
    )


