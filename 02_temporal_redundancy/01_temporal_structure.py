# VIDEO TEMPORAL STATISTICS
# ============================================================

def compute_video_temporal_statistics(
    df: pd.DataFrame,
) -> Tuple[pd.DataFrame, pd.DataFrame]:

    print_step("Computing video-level temporal statistics")

    # Sort globally first.
    df = df.sort_values(
        [
            "video_id",
            "frame_id",
        ]
    ).reset_index(drop=True)

    # --------------------------------------------------------
    # Frame-to-frame differences
    # --------------------------------------------------------

    df["frame_id_diff"] = (
        df
        .groupby("video_id")["frame_id"]
        .diff()
    )

    # First frame of every video has no previous frame.
    df["is_first_frame"] = (
        df["frame_id_diff"].isna()
    )

    df["is_adjacent"] = (
        df["frame_id_diff"] == 1
    )

    df["has_frame_gap"] = (
        df["frame_id_diff"].fillna(1) > 1
    )

    # Negative differences should not happen after sorting.
    df["has_backward_jump"] = (
        df["frame_id_diff"].fillna(0) < 0
    )

    # --------------------------------------------------------
    # Aggregate per video
    # --------------------------------------------------------

    rows = []

    for video_id, group in df.groupby(
        "video_id",
        sort=False,
    ):

        frame_ids = group["frame_id"].to_numpy()

        n_frames = len(frame_ids)

        min_frame_id = int(frame_ids.min())
        max_frame_id = int(frame_ids.max())

        span = max_frame_id - min_frame_id + 1

        expected_transitions = max(
            n_frames - 1,
            0,
        )

        observed_transitions = expected_transitions

        if expected_transitions > 0:

            diffs = np.diff(frame_ids)

            adjacent_transitions = int(
                np.sum(diffs == 1)
            )

            gap_count = int(
                np.sum(diffs > 1)
            )

            backward_count = int(
                np.sum(diffs < 0)
            )

            mean_gap = float(
                np.mean(diffs)
            )

            median_gap = float(
                np.median(diffs)
            )

            max_gap = int(
                np.max(diffs)
            )

        else:

            adjacent_transitions = 0
            gap_count = 0
            backward_count = 0
            mean_gap = 0.0
            median_gap = 0.0
            max_gap = 0

        continuity_ratio = (
            adjacent_transitions / expected_transitions
            if expected_transitions > 0
            else 1.0
        )

        # Approximate duration.
        #
        # This is based on frame-ID span and the configured
        # expected sampling interval.
        estimated_duration_seconds = (
            span * EXPECTED_FRAME_INTERVAL_SECONDS
        )

        estimated_duration_minutes = (
            estimated_duration_seconds / 60.0
        )

        # ----------------------------------------------------
        # Split / shard information
        # ----------------------------------------------------

        splits = sorted(
            group["split"].unique().tolist()
        )

        shards = sorted(
            group["shard"].unique().tolist()
        )

        rows.append(
            {
                "video_id": video_id,

                "split": "|".join(splits),

                "num_shards": len(shards),

                "shards": "|".join(shards),

                "num_frames": n_frames,

                "min_frame_id": min_frame_id,

                "max_frame_id": max_frame_id,

                "frame_id_span": span,

                "expected_transitions": expected_transitions,

                "adjacent_transitions": adjacent_transitions,

                "gap_count": gap_count,

                "backward_jump_count": backward_count,

                "continuity_ratio": continuity_ratio,

                "mean_frame_id_gap": mean_gap,

                "median_frame_id_gap": median_gap,

                "max_frame_id_gap": max_gap,

                "estimated_duration_seconds":
                    estimated_duration_seconds,

                "estimated_duration_minutes":
                    estimated_duration_minutes,

                "spans_multiple_shards":
                    len(shards) > 1,

                "has_frame_id_gap":
                    gap_count > 0,
            }
        )

    video_stats = pd.DataFrame(rows)

    # --------------------------------------------------------
    # Temporal gap table
    # --------------------------------------------------------

    gap_rows = []

    for video_id, group in df.groupby(
        "video_id",
        sort=False,
    ):

        group = group.sort_values(
            "frame_id"
        )

        frame_ids = group["frame_id"].to_numpy()

        if len(frame_ids) < 2:
            continue

        diffs = np.diff(frame_ids)

        gap_indices = np.where(
            diffs > 1
        )[0]

        for idx in gap_indices:

            gap_rows.append(
                {
                    "video_id": video_id,

                    "previous_frame_id":
                        int(frame_ids[idx]),

                    "next_frame_id":
                        int(frame_ids[idx + 1]),

                    "frame_id_gap":
                        int(diffs[idx]),

                    "missing_frame_count":
                        int(diffs[idx] - 1),
                }
            )

    gap_df = pd.DataFrame(
        gap_rows,
        columns=[
            "video_id",
            "previous_frame_id",
            "next_frame_id",
            "frame_id_gap",
            "missing_frame_count",
        ],
    )

    return video_stats, gap_df


# ============================================================
# ADJACENT TEMPORAL PAIRS
# ============================================================

def build_adjacent_frame_statistics(
    df: pd.DataFrame,
) -> pd.DataFrame:

    print_step("Building adjacent temporal frame statistics")

    df = df.sort_values(
        [
            "video_id",
            "frame_id",
        ]
    ).reset_index(drop=True)

    rows = []

    for video_id, group in df.groupby(
        "video_id",
        sort=False,
    ):

        group = group.sort_values(
            "frame_id"
        ).reset_index(drop=True)

        if len(group) < 2:
            continue

        frame_ids = group["frame_id"].to_numpy()

        for i in range(len(group) - 1):

            frame_a = int(frame_ids[i])
            frame_b = int(frame_ids[i + 1])

            gap = frame_b - frame_a

            rows.append(
                {
                    "video_id": video_id,

                    "split":
                        group.loc[i, "split"],

                    "shard_a":
                        group.loc[i, "shard"],

                    "shard_b":
                        group.loc[i + 1, "shard"],

                    "frame_id_a":
                        frame_a,

                    "frame_id_b":
                        frame_b,

                    "frame_id_distance":
                        gap,

                    "is_temporally_adjacent":
                        gap == 1,

                    "estimated_time_distance_seconds":
                        gap
                        * EXPECTED_FRAME_INTERVAL_SECONDS,

                    "hr_filename_a":
                        group.loc[i, "hr_filename"],

                    "hr_filename_b":
                        group.loc[i + 1, "hr_filename"],
                }
            )

    pair_df = pd.DataFrame(rows)

    print(
        "Temporal transitions:",
        format_number(len(pair_df)),
    )

    if len(pair_df) > 0:

        adjacent_count = int(
            pair_df[
                "is_temporally_adjacent"
            ].sum()
        )

        print(
            "Adjacent transitions:",
            format_number(adjacent_count),
        )

        print(
            "Non-adjacent transitions:",
            format_number(
                len(pair_df) - adjacent_count
            ),
        )

    return pair_df


