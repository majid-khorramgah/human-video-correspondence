def analyze_resolutions(
    dataset_root: Path,
    sample_size: int,
):
    print_section("IMAGE RESOLUTION / FORMAT ANALYSIS")

    modality_files = collect_modality_files(
        dataset_root
    )

    rows = []

    overall_counts = defaultdict(Counter)

    for modality, files in modality_files.items():

        sample = deterministic_sample(
            files,
            sample_size,
        )

        print(
            f"{modality}: "
            f"{len(files):,} files | "
            f"inspecting {len(sample):,}"
        )

        resolution_counter = Counter()
        format_counter = Counter()
        mode_counter = Counter()

        readable = 0
        unreadable = 0

        file_sizes = []

        for path in sample:

            info = inspect_image(path)

            if info["readable"] is True:
                readable += 1

                resolution = (
                    f"{info['width']}x"
                    f"{info['height']}"
                )

                resolution_counter[
                    resolution
                ] += 1

                if info["format"]:
                    format_counter[
                        info["format"]
                    ] += 1

                if info["mode"]:
                    mode_counter[
                        info["mode"]
                    ] += 1

            elif info["readable"] is False:
                unreadable += 1

            try:
                file_sizes.append(
                    path.stat().st_size
                )
            except OSError:
                pass

        dominant_resolution = (
            resolution_counter.most_common(1)[0][0]
            if resolution_counter
            else None
        )

        expected_resolution = None

        if modality.endswith("_HR"):
            expected_resolution = (
                f"{EXPECTED_HR_SIZE[0]}x"
                f"{EXPECTED_HR_SIZE[1]}"
            )

        elif modality.endswith("_LR"):
            expected_resolution = (
                f"{EXPECTED_LR_SIZE[0]}x"
                f"{EXPECTED_LR_SIZE[1]}"
            )

        rows.append(
            {
                "modality": modality,
                "total_files": len(files),
                "sampled_files": len(sample),
                "readable_files": readable,
                "unreadable_files": unreadable,
                "expected_resolution": expected_resolution,
                "dominant_resolution": dominant_resolution,
                "resolution_match_rate": (
                    resolution_counter[
                        expected_resolution
                    ]
                    / readable
                    if expected_resolution
                    and readable
                    else None
                ),
                "formats": "|".join(
                    f"{k}:{v}"
                    for k, v in format_counter.items()
                ),
                "modes": "|".join(
                    f"{k}:{v}"
                    for k, v in mode_counter.items()
                ),
                "resolution_counts": "|".join(
                    f"{k}:{v}"
                    for k, v in resolution_counter.items()
                ),
                "mean_file_size_bytes": (
                    statistics.mean(file_sizes)
                    if file_sizes
                    else None
                ),
                "median_file_size_bytes": (
                    statistics.median(file_sizes)
                    if file_sizes
                    else None
                ),
            }
        )

        for resolution, count in resolution_counter.items():
            overall_counts[
                modality
            ][resolution] += count

    return rows


