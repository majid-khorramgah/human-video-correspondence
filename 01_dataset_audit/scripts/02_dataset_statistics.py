def load_youtube_links(
    links_file: Optional[Path],
) -> Dict[str, Dict]:

    mapping = {}

    if links_file is None:
        return mapping

    if not links_file.exists():
        print(
            f"WARNING: YouTube links file not found: "
            f"{links_file}"
        )
        return mapping

    current_block = ""

    with open(
        links_file,
        "r",
        encoding="utf-8",
        errors="replace",
    ) as f:

        content = f.read()

    blocks = content.split(
        "--------------------------------------------------"
    )

    for block in blocks:

        file_match = re.search(
            r"File:\s*(.*)",
            block,
        )

        id_match = re.search(
            r"id:\s*(.*)",
            block,
        )

        if not id_match:
            continue

        video_id = id_match.group(1).strip()

        original_file = (
            file_match.group(1).strip()
            if file_match
            else ""
        )

        mapping[video_id] = {
            "video_id": video_id,
            "original_file": original_file,
        }

    return mapping


