def parse_frame_filename(filename: str):
    """
    Example:

    frame_0000033_-Hs-zuBOlQE.jpg

    Returns:

    frame_id = 33
    video_id = -Hs-zuBOlQE
    extension = jpg
    """

    match = FRAME_PATTERN.match(filename)

    if not match:
        return None

    frame_id = int(match.group(1))
    video_id = match.group(2)
    extension = match.group(3).lower()

    return {
        "frame_id": frame_id,
        "video_id": video_id,
        "extension": extension,
    }


