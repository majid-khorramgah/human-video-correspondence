def analyze_youtube_metadata(
    video_statistics: List[Dict],
    youtube_mapping: Dict[str, Dict],
):

    rows = []

    matched = 0
    unmatched = 0

    for video in video_statistics:

        video_id = video["video_id"]

        metadata = youtube_mapping.get(
            video_id
        )

        if metadata:
            matched += 1

            rows.append(
                {
                    "video_id": video_id,
                    "frames": video["frames"],
                    "split": video["splits"],
                    "num_shards": video[
                        "num_shards"
                    ],
                    "original_file": metadata.get(
                        "original_file",
                        "",
                    ),
                    "metadata_found": True,
                }
            )

        else:
            unmatched += 1

            rows.append(
                {
                    "video_id": video_id,
                    "frames": video["frames"],
                    "split": video["splits"],
                    "num_shards": video[
                        "num_shards"
                    ],
                    "original_file": "",
                    "metadata_found": False,
                }
            )

    summary = {
        "total_dataset_videos": len(
            video_statistics
        ),
        "youtube_mapping_entries": len(
            youtube_mapping
        ),
        "matched_videos": matched,
        "unmatched_videos": unmatched,
        "match_rate_percent": (
            100.0 * matched / len(video_statistics)
            if video_statistics
            else 0
        ),
    }

    return rows, summary


