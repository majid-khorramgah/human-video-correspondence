def deterministic_sample(
    paths: List[Path],
    sample_size: int,
) -> List[Path]:

    if sample_size <= 0:
        return paths

    if len(paths) <= sample_size:
        return paths

    step = len(paths) / sample_size

    result = []

    for i in range(sample_size):
        index = min(
            int(i * step),
            len(paths) - 1,
        )

        result.append(paths[index])

    return result


def collect_modality_files(
    dataset_root: Path,
):
    result = {
        modality: []
        for modality in EXPECTED_MODALITIES
    }

    for shard in discover_shards(dataset_root):

        for split in EXPECTED_SPLITS:

            split_root = shard / split

            if not split_root.exists():
                continue

            for modality in EXPECTED_MODALITIES:

                directory = split_root / modality

                if not directory.exists():
                    continue

                try:
                    for item in directory.iterdir():

                        if item.is_file():
                            result[modality].append(item)

                except PermissionError:
                    print(
                        f"WARNING: Permission denied: "
                        f"{directory}"
                    )

    return result


