def discover_shards(dataset_root: Path) -> List[Path]:
    shards = []

    if not dataset_root.exists():
        raise FileNotFoundError(
            f"Dataset root does not exist: {dataset_root}"
        )

    for item in dataset_root.iterdir():

        if not item.is_dir():
            continue

        if SHARD_PATTERN.match(item.name):
            shards.append(item)

    shards.sort(
        key=lambda p: (
            int(SHARD_PATTERN.match(p.name).group(1))
        )
    )

    return shards


def discover_master_index(
    integrity_dir: Path,
) -> Optional[Path]:

    candidates = [
        integrity_dir / "master_index.csv",
        integrity_dir / "master_dataset_index.csv",
    ]

    for candidate in candidates:
        if candidate.exists():
            return candidate

    return None


