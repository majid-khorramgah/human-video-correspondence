def create_video_record(
    video_id: str,
):
    return {
        "video_id": video_id,
        "frames": 0,
        "splits": set(),
        "shards": set(),
        "frame_ids": [],
        "extensions": Counter(),
        "first_frame_id": None,
        "last_frame_id": None,
    }


def finalize_video_record(
    record: Dict,
) -> Dict:

    frame_ids = sorted(record["frame_ids"])

    gaps = 0
    gap_total = 0
    min_step = None
    max_step = None

    if len(frame_ids) > 1:

        steps = [
            frame_ids[i + 1] - frame_ids[i]
            for i in range(len(frame_ids) - 1)
        ]

        min_step = min(steps)
        max_step = max(steps)

        for step in steps:
            if step != 1:
                gaps += 1
                gap_total += max(0, step - 1)

    first_frame = (
        frame_ids[0]
        if frame_ids
        else None
    )

    last_frame = (
        frame_ids[-1]
        if frame_ids
        else None
    )

    return {
        "video_id": record["video_id"],
        "frames": record["frames"],
        "splits": "|".join(
            sorted(record["splits"])
        ),
        "shards": "|".join(
            sorted(record["shards"])
        ),
        "num_shards": len(record["shards"]),
        "first_frame_id": first_frame,
        "last_frame_id": last_frame,
        "frame_id_span": (
            last_frame - first_frame + 1
            if first_frame is not None
            and last_frame is not None
            else 0
        ),
        "frame_id_gaps": gaps,
        "missing_frame_ids": gap_total,
        "min_frame_step": min_step,
        "max_frame_step": max_step,
        "continuous": gaps == 0,
        "extensions": "|".join(
            f"{k}:{v}"
            for k, v in sorted(
                record["extensions"].items()
            )
        ),
    }


