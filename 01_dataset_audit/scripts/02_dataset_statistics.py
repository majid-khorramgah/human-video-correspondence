def modality_statistics_from_index(
    master_index: Path,
):
    print_section("MODALITY STATISTICS")

    counters = {
        modality: {
            "present": 0,
            "missing": 0,
        }
        for modality in EXPECTED_MODALITIES
    }

    total = 0

    for row in iter_master_index(master_index):

        total += 1

        for modality in EXPECTED_MODALITIES:

            value = (
                row.get(
                    "has_" + modality,
                    "",
                )
                or ""
            ).lower()

            if value in {
                "true",
                "1",
                "yes",
            }:
                counters[
                    modality
                ]["present"] += 1
            else:
                counters[
                    modality
                ]["missing"] += 1

    rows = []

    for modality in EXPECTED_MODALITIES:

        present = counters[
            modality
        ]["present"]

        missing = counters[
            modality
        ]["missing"]

        rows.append(
            {
                "modality": modality,
                "dataset_frames": total,
                "present": present,
                "missing": missing,
                "coverage_percent": (
                    100.0 * present / total
                    if total
                    else 0
                ),
            }
        )

    return rows


