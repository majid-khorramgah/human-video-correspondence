def inspect_image(path: Path):
    """
    Read image header / metadata.

    Does not decode the full image unnecessarily.
    """

    if not PIL_AVAILABLE:
        return {
            "readable": None,
            "width": None,
            "height": None,
            "format": None,
            "mode": None,
        }

    try:
        with Image.open(path) as img:
            return {
                "readable": True,
                "width": img.width,
                "height": img.height,
                "format": img.format,
                "mode": img.mode,
            }

    except Exception:
        return {
            "readable": False,
            "width": None,
            "height": None,
            "format": None,
            "mode": None,
        }


