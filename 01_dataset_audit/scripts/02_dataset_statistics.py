def iter_master_index(
    master_index: Path,
):
    """
    Streaming CSV reader.

    Important because master_index.csv can be >200 MB.
    """

    with open(
        master_index,
        "r",
        encoding="utf-8-sig",
        errors="replace",
        newline="",
    ) as f:

        reader = csv.DictReader(f)

        for row in reader:
            yield row


