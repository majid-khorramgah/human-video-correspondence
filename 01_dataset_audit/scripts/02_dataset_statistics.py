def analyze_master_index(
    master_index: Path,
):
    print_section("READING MASTER INDEX")

    video_records = {}

    split_frames = Counter()
    split_videos = defaultdict(set)

    shard_frames = Counter()
    shard_videos = defaultdict(set)

    frame_extensions = Counter()

    modality_presence = Counter()

    frame_id_values = []

    total_rows = 0

    malformed_rows = 0

    start_time = time.time()

    for row in iter_master_index(master_index):

        total_rows += 1

        video_id = (
            row.get("video_id", "")
            or ""
        ).strip()

        frame_id = safe_int(
            row.get("frame_id")
        )

        split = (
            row.get("split", "")
            or ""
        ).strip()

        shard = (
            row.get("shard", "")
            or ""
        ).strip()

        if not video_id or frame_id is None:
            malformed_rows += 1
            continue

        # ---------------------------------------------------------
        # Video
        # ---------------------------------------------------------

        if video_id not in video_records:
            video_records[video_id] = create_video_record(
                video_id
            )

        record = video_records[video_id]

        record["frames"] += 1
        record["frame_ids"].append(frame_id)

        if split:
            record["splits"].add(split)

        if shard:
            record["shards"].add(shard)

        # ---------------------------------------------------------
        # Split
        # ---------------------------------------------------------

        split_frames[split] += 1
        split_videos[split].add(video_id)

        # ---------------------------------------------------------
        # Shard
        # ---------------------------------------------------------

        shard_frames[shard] += 1
        shard_videos[shard].add(video_id)

        # ---------------------------------------------------------
        # Extension
        # ---------------------------------------------------------

        extension = (
            row.get("hr_extension", "")
            or ""
        ).lower()

        if extension:
            frame_extensions[extension] += 1

        # ---------------------------------------------------------
        # Modalities
        # ---------------------------------------------------------

        for modality in EXPECTED_MODALITIES:

            column = (
                "has_" + modality
            )

            value = (
                row.get(column, "")
                or ""
            ).strip().lower()

            if value in {
                "true",
                "1",
                "yes",
            }:
                modality_presence[modality] += 1

        frame_id_values.append(frame_id)

    elapsed = time.time() - start_time

    print(
        f"Rows processed: {total_rows:,}"
    )

    print(
        f"Videos discovered: {len(video_records):,}"
    )

    print(
        f"Time: {elapsed / 60:.2f} minutes"
    )

    # -------------------------------------------------------------
    # Finalize videos
    # -------------------------------------------------------------

    video_statistics = []

    for record in video_records.values():
        video_statistics.append(
            finalize_video_record(record)
        )

    video_statistics.sort(
        key=lambda x: (
            -x["frames"],
            x["video_id"],
        )
    )

    # -------------------------------------------------------------
    # Split statistics
    # -------------------------------------------------------------

    split_statistics = []

    for split in EXPECTED_SPLITS:

        frames = split_frames[split]
        videos = len(split_videos[split])

        split_statistics.append(
            {
                "split": split,
                "frames": frames,
                "videos": videos,
                "mean_frames_per_video": (
                    frames / videos
                    if videos
                    else 0
                ),
                "percentage_of_frames": 0,
                "percentage_of_videos": 0,
            }
        )

    total_frames = sum(
        split_frames.values()
    )

    total_videos = len(video_records)

    for row in split_statistics:

        row["percentage_of_frames"] = (
            100.0 * row["frames"] / total_frames
            if total_frames
            else 0
        )

        row["percentage_of_videos"] = (
            100.0 * row["videos"] / total_videos
            if total_videos
            else 0
        )

    # -------------------------------------------------------------
    # Shard statistics
    # -------------------------------------------------------------

    shard_statistics = []

    for shard in sorted(shard_frames):

        shard_statistics.append(
            {
                "shard": shard,
                "frames": shard_frames[shard],
                "videos": len(
                    shard_videos[shard]
                ),
                "percentage_of_frames": (
                    100.0
                    * shard_frames[shard]
                    / total_frames
                    if total_frames
                    else 0
                ),
                "expected_capacity": 100000,
                "capacity_utilization_percent": (
                    100.0
                    * shard_frames[shard]
                    / 100000
                ),
            }
        )

    # -------------------------------------------------------------
    # Frame statistics
    # -------------------------------------------------------------

    frame_summary = summarize_numeric(
        frame_id_values
    )

    frames_per_video = [
        row["frames"]
        for row in video_statistics
    ]

    frame_count_summary = summarize_numeric(
        frames_per_video
    )

    # -------------------------------------------------------------
    # Cross-shard videos
    # -------------------------------------------------------------

    cross_shard_videos = [
        row
        for row in video_statistics
        if row["num_shards"] > 1
    ]

    # -------------------------------------------------------------
    # Split-crossing videos
    # -------------------------------------------------------------

    cross_split_videos = [
        row
        for row in video_statistics
        if len(
            row["splits"].split("|")
        ) > 1
    ]

    return {
        "total_rows": total_rows,
        "malformed_rows": malformed_rows,
        "video_statistics": video_statistics,
        "split_statistics": split_statistics,
        "shard_statistics": shard_statistics,
        "frame_summary": frame_summary,
        "frame_count_summary": frame_count_summary,
        "frames_per_video": frames_per_video,
        "frame_extensions": dict(
            frame_extensions
        ),
        "modality_presence": dict(
            modality_presence
        ),
        "cross_shard_videos": cross_shard_videos,
        "cross_split_videos": cross_split_videos,
    }


