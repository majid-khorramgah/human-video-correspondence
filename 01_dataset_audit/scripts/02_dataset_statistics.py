    rows = []

    modalities = (
        EXPECTED_MODALITIES
        if include_masks
        else [
            "Img_HR",
            "Img_LR",
        ]
    )

    for modality in modalities:

        total_files = 0
        total_bytes = 0

        sizes = []

        for shard in discover_shards(dataset_root):

            for split in EXPECTED_SPLITS:

                directory = (
                    shard
                    / split
                    / modality
                )

                if not directory.exists():
                    continue

                try:
                    for path in directory.iterdir():

                        if not path.is_file():
                            continue

                        try:
                            size = path.stat().st_size
                        except OSError:
                            continue

                        total_files += 1
                        total_bytes += size

                        sizes.append(size)

                except PermissionError:
                    continue

        summary = summarize_numeric(
            sizes
        )

        rows.append(
            {
                "modality": modality,
                "files": total_files,
                "total_bytes": total_bytes,
                "total_size_human": format_bytes(
                    total_bytes
                ),
                "mean_bytes": summary["mean"],
                "median_bytes": summary["median"],
                "min_bytes": summary["min"],
                "max_bytes": summary["max"],
                "p05_bytes": summary["p05"],
                "p25_bytes": summary["p25"],
                "p75_bytes": summary["p75"],
                "p95_bytes": summary["p95"],
            }
        )

        print(
            f"{modality}: "
            f"{total_files:,} files | "
            f"{format_bytes(total_bytes)}"
        )

        # Release memory
        del sizes

    return rows


